/**
 * Validates an EMA Agent configuration.
 */
export function validateEmaAgentConfig(config: Partial<EmaAgentConfig>): {
  valid: boolean;
  errors: string[];
} {
  const errors: string[] = [];
  if (config.id && !/^[a-zA-Z0-9_]+$/.test(config.id)) {
    errors.push(
      "Agent ID must contain only letters, numbers, and underscores (no hyphens or spaces).",
    );
  }
  if (config.name !== undefined && config.name.trim().length === 0) {
    errors.push("Agent name cannot be empty.");
  }
  if (config.title !== undefined && config.title.trim().length === 0) {
    errors.push("Agent title cannot be empty.");
  }
  return {
    valid: errors.length === 0,
    errors,
  };
}

/**
 * Generates the YAML content for Penguin's agent_state/system_config.yaml.
 */
export function generatePenguinSystemConfigYaml(config: Partial<EmaAgentConfig>): string {
  const name = config.name || DEFAULT_EMA_CONFIG.name;
  const description = config.bio || DEFAULT_EMA_CONFIG.bio;

  return `# Penguin Agent System Configuration
# Generated by @prism-shadow/ema
version: 1
name: "${name.replace(/"/g, '\\"')}"
description: "${description.replace(/"/g, '\\"')}"

model:
  thinking_level: "medium"

hooks:
  enabled: true
`;
}

/**
 * Find agent preset by ID.
 */
export function getAgentPreset(presetId: string) {
  return EMA_AGENT_PRESETS.find((p) => p.id === presetId);
}

/**
 * Find personality feature preset by ID.
 */
export function getPersonalityPreset(presetId: string) {
  return PERSONALITY_FEATURE_PRESETS.find((p) => p.id === presetId);
}

